// Builds single-file bundles:
//   dist/war-train.bundle.js          — all overlay code in one script (for self-hosting)
//   dist/streamelements/widget.{html,css,js} + fields.json — paste into a StreamElements Custom Widget
// Usage: node tools/build.cjs
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const files = ['core/util.js', 'core/config.js', 'core/sound.js', 'fx/particles.js', 'train/parts.js', 'fx/strikes.js', 'train/wagons.js', 'show/run.js', 'events/controller.js', 'events/adapters.js', 'main.js'];
const bundle = `/* War Train overlay bundle — generated by tools/build.cjs, do not edit */\n` +
  files.map((f) => `/* ---- js/${f} ---- */\n` + fs.readFileSync(path.join(root, 'js', f), 'utf8')).join('\n');
const dist = path.join(root, 'dist');
const se = path.join(dist, 'streamelements');
fs.mkdirSync(se, { recursive: true });
fs.writeFileSync(path.join(dist, 'war-train.bundle.js'), bundle);

fs.writeFileSync(path.join(se, 'widget.html'), '<div id="wt-stage"><canvas id="wt-canvas" width="1920" height="1080"></canvas></div>\n');
const css = fs.readFileSync(path.join(root, 'css/overlay.css'), 'utf8').replace(/@font-face[^\n]*\n/g, '');
fs.writeFileSync(path.join(se, 'widget.css'),
  "@import url('https://fonts.googleapis.com/css2?family=Black+Ops+One&family=Oswald:wght@500;700&display=block');\n" + css);
fs.writeFileSync(path.join(se, 'widget.js'), bundle + `
/* ---- StreamElements boot ---- */
window.addEventListener('onWidgetLoad', function (obj) {
  var f = (obj && obj.detail && obj.detail.fieldData) || {};
  window.WAR_TRAIN_CONFIG = {
    source: 'streamelements',
    mode: f.loopDemo === true || f.loopDemo === 'true' ? 'loop' : 'events',
    quality: f.quality || 'high',
    maxWagonsPerRun: +f.maxGifters || 6,
    theme: f.theme || 'steel',
    warIntensity: f.war != null ? +f.war : 1,
    persist: true,
    sound: { enabled: f.soundEnabled === true || f.soundEnabled === 'true', volume: f.volume != null ? +f.volume : 0.5 },
    labels: {
      gifter: f.labelGifter || 'SUB GIFTER', hype: f.labelHype || 'HYPE TRAIN', blackops: f.labelBlackops || 'BLACK OPS',
      warzone: f.labelWarzone || 'WARZONE', thanks: f.labelThanks || 'THANK YOU, SUB GIFTERS!'
    }
  };
  WT.boot();
});
`);
fs.writeFileSync(path.join(se, 'fields.json'), JSON.stringify({
  loopDemo: { type: 'checkbox', label: 'Loop demo train (testing only)', value: false },
  quality: { type: 'dropdown', label: 'Effects quality', value: 'high', options: { high: 'High', low: 'Low (weak PCs)' } },
  theme: { type: 'dropdown', label: 'Colour theme', value: 'steel', options: { steel: 'Blue steel', chrome: 'Chrome', blackgold: 'Black & gold', crimson: 'Crimson ops', desert: 'Desert storm', arctic: 'Arctic', toxic: 'Toxic' } },
  war: { type: 'slider', label: 'Battlefield intensity', value: 1, min: 0, max: 1, step: 0.1 },
  maxGifters: { type: 'number', label: 'Max gifter wagons per pass', value: 6, min: 1, max: 10 },
  soundEnabled: { type: 'checkbox', label: 'Sound (placeholder synth)', value: false },
  volume: { type: 'slider', label: 'Volume', value: 0.5, min: 0, max: 1, step: 0.05 },
  labelGifter: { type: 'text', label: 'Gifter wagon label', value: 'SUB GIFTER' },
  labelHype: { type: 'text', label: 'Hype wagon label', value: 'HYPE TRAIN' },
  labelBlackops: { type: 'text', label: 'Wagon 2 label', value: 'BLACK OPS' },
  labelWarzone: { type: 'text', label: 'Wagon 3 label', value: 'WARZONE' },
  labelThanks: { type: 'text', label: 'Celebration text', value: 'THANK YOU, SUB GIFTERS!' },
}, null, 2));
console.log('built dist/war-train.bundle.js and dist/streamelements/*');
